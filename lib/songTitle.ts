/**
 * Кегль названия разбора подбирается под само название.
 *
 * На телефоне заголовок стоит в узкой колонке рядом с обложкой, и один размер
 * на все названия означает выбор в пользу худшего случая: «Пьяные» набиралось
 * тем же кеглем, что и название из четырёх слов, хотя места рядом с ним
 * оставалось на полколонки. Теперь размер считается из двух ширин самого
 * названия, а подставляет их в формулу CSS (см. .song-title в globals.css):
 * ширину колонки знает только браузер, и без него её пришлось бы мерить после
 * гидратации — то есть показывать один кегль и на глазах менять на другой.
 *
 * Ширины букв замерены `canvas.measureText` для Spectral 500 — тем же способом,
 * что и в lib/chordpro/spacing.ts, но это другой шрифт (заголовок набран
 * шрифтом --font-display) и другой letter-spacing, поэтому таблица своя.
 *
 * Точность здесь нужна не абсолютная: ошибка в пару процентов сдвигает кегль на
 * те же пару процентов, а от переполнения колонки страхуют и запас SAFETY, и
 * обрезка тремя строками.
 */

/** Ширины глифов Spectral 500 в долях кегля: [символы, ширина]. */
const GLYPH_GROUPS: [string, number][] = [
  ['.,!;:\'()/', 0.25],
  ['l', 0.3],
  ['ij', 0.32],
  ['f', 0.35],
  ['t*', 0.36],
  ['-', 0.37],
  ['rIJ', 0.4],
  ['s', 0.43],
  ['«»', 0.44],
  ['з"', 0.45],
  ['г', 0.46],
  ['cvyсу?', 0.48],
  ['ezеё', 0.49],
  ['aат–_', 0.5],
  ['0123456789xвхьэ+', 0.51],
  ['oSбдло', 0.54],
  ['gчя', 0.55],
  ['q', 0.56],
  ['bdkpuкр', 0.57],
  ['hnпъ', 0.59],
  ['нцГ', 0.6],
  ['ий', 0.61],
  ['F', 0.62],
  ['L', 0.64],
  ['PЗР', 0.65],
  ['EZЕЁЬ', 0.66],
  ['BВ…', 0.67],
  ['RTБТ', 0.68],
  ['ф', 0.69],
  ['мЯ&', 0.71],
  ['CЛСУ', 0.72],
  ['KYДКЭ', 0.73],
  ['ЧЪ', 0.74],
  ['wVXХ', 0.75],
  ['AыюА%', 0.76],
  ['G', 0.77],
  ['D', 0.78],
  ['жПЦ', 0.79],
  ['NOQО', 0.8],
  ['@', 0.81],
  ['HUшН', 0.82],
  ['ИЙ', 0.83],
  ['щФ', 0.85],
  ['m', 0.87],
  ['MМЫ', 0.97],
  ['W—', 1],
  ['Ж', 1.03],
  ['ШЮ', 1.07],
  ['Щ', 1.08],
];

const GLYPH: Record<string, number> = {};
for (const [chars, width] of GLYPH_GROUPS) {
  for (const ch of chars) GLYPH[ch] = width;
}

/** Незнакомый символ — по средней букве. */
const UNKNOWN_GLYPH = 0.55;

/** `letter-spacing` заголовка, см. .song-title. Отрицательный — буквы поджаты. */
const LETTER_SPACING = -0.015;

/** Пробел между словами. */
const SPACE = 0.25;

/**
 * Значок подтверждения с неразрывным пробелом перед ним — хвост за последним
 * словом.
 *
 * Значок растёт вместе с названием (см. `.song-title .verified-badge` в
 * globals.css), поэтому доли кегля здесь — не оценка, а точное значение.
 *
 * Вычесть его из ширины колонки в CSS было бы нельзя при всём желании: em
 * внутри `font-size` считается от кегля РОДИТЕЛЯ, а не от вычисляемого, и такой
 * запас отмерялся бы от 16px заголовка. Поэтому хвост прибавляется к ширине
 * слова — что то же самое, только без круговой ссылки.
 */
const BADGE = 0.72;
const BADGE_TAIL = SPACE + BADGE;

/** Запас на округления при отрисовке: лучше кегль мельче, чем строка не влезла. */
const SAFETY = 1.015;

export interface TitleFit {
  /** Ширина названия одной строкой, в долях кегля. */
  oneLine: number;
  /** Ширина самого длинного слова: перенести его некуда, оно и задаёт потолок. */
  longestWord: number;
  /** Слов в названии — от них зависит, на сколько строк рассчитывать потолок. */
  words: number;
}

/** Ширина слова в долях кегля. */
function wordWidth(word: string): number {
  let width = 0;
  for (const ch of word) width += (GLYPH[ch] ?? UNKNOWN_GLYPH) + LETTER_SPACING;
  return width;
}

/**
 * Две ширины названия, из которых CSS считает кегль: влезет ли оно целиком в
 * строку (`oneLine`) и влезет ли самое длинное слово (`longestWord`) — перенести
 * его некуда, и оно задаёт потолок.
 */
export function titleFit(title: string, verified = false): TitleFit {
  const words = title.split(/\s+/).filter(Boolean);
  const round = (n: number) => Math.round(n * SAFETY * 100) / 100;
  if (words.length === 0) return { oneLine: SAFETY, longestWord: SAFETY, words: 0 };

  const widths = words.map(wordWidth);
  // Значок с неразрывным пробелом переносится вместе с последним словом, то
  // есть входит в его ширину — и в самое длинное слово, если последнее им и
  // оказалось.
  if (verified) widths[widths.length - 1] += BADGE_TAIL;

  return {
    oneLine: round(
      widths.reduce((a, b) => a + b, 0) + (words.length - 1) * (SPACE + LETTER_SPACING),
    ),
    longestWord: round(Math.max(...widths)),
    words: words.length,
  };
}
