/**
 * Кегль названия разбора подбирается под само название.
 *
 * На телефоне заголовок стоит в узкой колонке рядом с обложкой, и один размер
 * на все названия означает выбор в пользу худшего случая: «Пьяные» набиралось
 * тем же кеглем, что и название из четырёх слов, хотя места рядом с ним
 * оставалось на полколонки. Теперь размер считается из двух ширин самого
 * названия, а подставляет их в формулу CSS (см. .song-title в globals.css):
 * ширину колонки знает только браузер, и без него её пришлось бы мерить после
 * гидратации — то есть показывать один кегль и на глазах менять на другой.
 *
 * Ширины букв замерены `canvas.measureText` для Spectral 500 — тем же способом,
 * что и в lib/chordpro/spacing.ts, но это другой шрифт (заголовок набран
 * шрифтом --font-display) и другой letter-spacing, поэтому таблица своя.
 *
 * Точность здесь нужна не абсолютная: ошибка в пару процентов сдвигает кегль на
 * те же пару процентов, а от переполнения колонки страхуют и запас SAFETY, и
 * обрезка тремя строками.
 */

/** Ширины глифов Spectral 500 в долях кегля: [символы, ширина]. */
const GLYPH_GROUPS: [string, number][] = [
  ['.,!;:\'()/', 0.25],
  ['l', 0.3],
  ['ij', 0.32],
  ['f', 0.35],
  ['t*', 0.36],
  ['-', 0.37],
  ['rIJ', 0.4],
  ['s', 0.43],
  ['«»', 0.44],
  ['з"', 0.45],
  ['г', 0.46],
  ['cvyсу?', 0.48],
  ['ezеё', 0.49],
  ['aат–_', 0.5],
  ['0123456789xвхьэ+', 0.51],
  ['oSбдло', 0.54],
  ['gчя', 0.55],
  ['q', 0.56],
  ['bdkpuкр', 0.57],
  ['hnпъ', 0.59],
  ['нцГ', 0.6],
  ['ий', 0.61],
  ['F', 0.62],
  ['L', 0.64],
  ['PЗР', 0.65],
  ['EZЕЁЬ', 0.66],
  ['BВ…', 0.67],
  ['RTБТ', 0.68],
  ['ф', 0.69],
  ['мЯ&', 0.71],
  ['CЛСУ', 0.72],
  ['KYДКЭ', 0.73],
  ['ЧЪ', 0.74],
  ['wVXХ', 0.75],
  ['AыюА%', 0.76],
  ['G', 0.77],
  ['D', 0.78],
  ['жПЦ', 0.79],
  ['NOQО', 0.8],
  ['@', 0.81],
  ['HUшН', 0.82],
  ['ИЙ', 0.83],
  ['щФ', 0.85],
  ['m', 0.87],
  ['MМЫ', 0.97],
  ['W—', 1],
  ['Ж', 1.03],
  ['ШЮ', 1.07],
  ['Щ', 1.08],
];

const GLYPH: Record<string, number> = {};
for (const [chars, width] of GLYPH_GROUPS) {
  for (const ch of chars) GLYPH[ch] = width;
}

/** Незнакомый символ — по средней букве. */
const UNKNOWN_GLYPH = 0.55;

/** `letter-spacing` заголовка, см. .song-title. Отрицательный — буквы поджаты. */
const LETTER_SPACING = -0.015;

/** Пробел между словами. */
const SPACE = 0.25;

/**
 * Значок подтверждения с неразрывным пробелом перед ним — хвост за последним
 * словом.
 *
 * Значок растёт вместе с названием (см. `.song-title .verified-badge` в
 * globals.css), поэтому доли кегля здесь — не оценка, а точное значение.
 *
 * Вычесть его из ширины колонки в CSS было бы нельзя при всём желании: em
 * внутри `font-size` считается от кегля РОДИТЕЛЯ, а не от вычисляемого, и такой
 * запас отмерялся бы от 16px заголовка. Поэтому хвост прибавляется к ширине
 * слова — что то же самое, только без круговой ссылки.
 */
const BADGE = 0.72;
const BADGE_TAIL = SPACE + BADGE;

/** Запас на округления при отрисовке: лучше кегль мельче, чем строка не влезла. */
const SAFETY = 1.015;

export interface TitleFit {
  /** Ширина колонки, при которой название ложится в одну строку, в долях кегля. */
  oneLine: number;
  /** То же для двух строк — наименьшая ширина, при которой хватает двух. */
  twoLines: number;
}

/** Ширина слова в долях кегля. */
function wordWidth(word: string): number {
  let width = 0;
  for (const ch of word) width += (GLYPH[ch] ?? UNKNOWN_GLYPH) + LETTER_SPACING;
  return width;
}

/** Промежуток между словами. */
const GAP = SPACE + LETTER_SPACING;

/** Сколько строк даст жадный перенос в колонке шириной `width`. */
function greedyLines(widths: number[], width: number): number {
  let lines = 1;
  let current = widths[0];
  for (let i = 1; i < widths.length; i++) {
    const next = current + GAP + widths[i];
    if (next <= width + 1e-9) current = next;
    else {
      lines += 1;
      current = widths[i];
    }
  }
  return lines;
}

/**
 * Наименьшая ширина колонки, при которой название укладывается в `limit` строк.
 *
 * Перебираем ширины всех возможных строк: строка — это всегда несколько подряд
 * идущих слов, поэтому ответом может быть только такая сумма. Проверяем их от
 * узкой к широкой ЖАДНЫМ переносом — тем же, каким ломает строки браузер:
 * оптимальная разбивка дала бы ширину меньше настоящей, и название вылезло бы
 * на лишнюю строку.
 */
function widthForLines(widths: number[], limit: number): number {
  const candidates: number[] = [];
  for (let i = 0; i < widths.length; i++) {
    let sum = widths[i];
    candidates.push(sum);
    for (let j = i + 1; j < widths.length; j++) {
      sum += GAP + widths[j];
      candidates.push(sum);
    }
  }
  // Уже самого длинного слова колонка быть не может: перенести его некуда, и
  // счёт строк тут обманчив — в узкой колонке слово встаёт на свою строку и
  // просто вылезает за край. Само оно тоже в кандидатах, так что нижняя
  // граница достижима.
  const floor = Math.max(...widths);
  candidates.sort((a, b) => a - b);
  for (const width of candidates) {
    if (width >= floor && greedyLines(widths, width) <= limit) return width;
  }
  return candidates[candidates.length - 1];
}

/**
 * Две ширины названия, из которых CSS считает кегль: сколько места нужно, чтобы
 * оно легло в одну строку и чтобы легло в две.
 *
 * Считаем именно строки, а не слова. Раньше потолок кегля зависел от числа слов,
 * и «я схавал опиат» — три слова — попадало в правило для длинных: название
 * вытягивалось в одну мелкую строку, хотя «я схавал» / «опиат» крупным кеглем
 * встают ровно по высоте обложки.
 */
export function titleFit(title: string, verified = false): TitleFit {
  const words = title.split(/\s+/).filter(Boolean);
  const round = (n: number) => Math.round(n * SAFETY * 100) / 100;
  if (words.length === 0) return { oneLine: SAFETY, twoLines: SAFETY };

  const widths = words.map(wordWidth);
  // Значок с неразрывным пробелом переносится вместе с последним словом, то
  // есть входит в его ширину.
  if (verified) widths[widths.length - 1] += BADGE_TAIL;

  return {
    oneLine: round(widths.reduce((a, b) => a + b, 0) + (words.length - 1) * GAP),
    twoLines: round(widthForLines(widths, 2)),
  };
}
