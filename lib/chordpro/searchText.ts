/**
 * Текст песни для поиска: название, исполнитель и сами слова — без разметки.
 *
 * Искать прямо по `body` нельзя: там аккорды в квадратных скобках и директивы
 * в фигурных, из-за чего фраза, разорванная аккордом (`дру[C]зья`), не
 * находится, а по запросу «am» находится половина каталога. Поэтому при
 * сохранении песни складываем очищенный текст в отдельную колонку.
 *
 * Чистый модуль без зависимостей — покрыт тестами.
 */

/** Убирает из строки ChordPro всю разметку, оставляя только слова. */
export function stripChordPro(body: string): string {
  return (
    body
      // директивы целиком: {start_of_chorus}, {comment: ...}
      .replace(/\{[^}\n]*\}/g, ' ')
      // аккорды в квадратных скобках
      .replace(/\[[^\]\n]*\]/g, '')
      // знаки серого текста — сами по себе не слова
      .replace(/%/g, ' ')
      // схлопываем пробелы и переносы
      .replace(/\s+/g, ' ')
      .trim()
  );
}

/**
 * Строка, по которой ищем: название + исполнитель + слова, в нижнем регистре.
 * Регистр снимаем заранее, чтобы поиск сравнивал без учёта регистра, не
 * заставляя БД приводить обе стороны на каждой строке.
 */
export function buildSearchText(input: {
  title: string;
  artist?: string | null;
  body: string;
}): string {
  return [input.title, input.artist ?? '', stripChordPro(input.body)]
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

/**
 * Потолок длины поискового запроса.
 *
 * Единственное пользовательское поле, у которого потолка не было вовсе, — при
 * том что ради потолков заведён целый [songLimits.ts](../songLimits.ts). А
 * стоит запрос дороже всех остальных: он приходит из адресной строки, поиск
 * СОЗНАТЕЛЬНО не кэшируется (`q` задаёт посетитель, и кэш по нему — бесконечное
 * множество ключей, см. lib/cache.ts), и каждый запрос уходит в базу. Ничего не
 * мешало прислать `?q=` на сотню килобайт и заставить Postgres искать эту
 * простыню подстрокой по всему каталогу.
 *
 * Ста символов хватает и строчке из песни, и полному «название — исполнитель».
 * Обрезка при этом не теряет результатов, а только добавляет: у `LIKE '%…%'`
 * короткая подстрока совпадает не реже длинной, поэтому обрезанный запрос
 * находит надмножество того, что нашёл бы целый.
 */
export const SEARCH_QUERY_MAX = 100;

/**
 * Запрос в том виде, в каком он уходит в базу: без краёв, в нижнем регистре и
 * не длиннее потолка.
 *
 * Отдельной функцией, потому что путей в базу два и они разные — обычный поиск
 * подстрокой (`searchQueryForLike` ниже) и подбор при опечатке
 * (`fuzzyMatchIds` в lib/songs.ts, он экранирования не делает вовсе). Потолок
 * обязан стоять на обоих, а два описания одного правила расходятся.
 */
export function normalizeSearchQuery(query: string | null | undefined): string | null {
  const q = query?.trim().toLowerCase();
  if (!q) return null;
  return q.slice(0, SEARCH_QUERY_MAX);
}

/**
 * Готовит пользовательский запрос к подстановке в `contains` (то есть в SQL
 * `LIKE`). Возвращает null, если искать нечего.
 *
 * `%` и `_` в LIKE — маски: без экранирования запрос «50%» превращался в
 * «покажи вообще всё», а «_» совпадал с любым символом. Prisma передаёт
 * значение параметром и не добавляет `ESCAPE`, поэтому работает escape-символ
 * PostgreSQL по умолчанию — обратный слеш. Его самого экранируем первым, иначе
 * добавленные ниже слеши экранировали бы друг друга.
 *
 * Экранирование идёт ПОСЛЕ обрезки: иначе потолок считался бы по строке со
 * слешами, и запрос из ста процентов усох бы до пятидесяти.
 */
export function searchQueryForLike(query: string | null | undefined): string | null {
  const q = normalizeSearchQuery(query);
  if (!q) return null;
  return q.replace(/[\\%_]/g, (ch) => `\\${ch}`);
}
