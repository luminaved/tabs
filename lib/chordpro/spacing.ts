const GLYPH: Record<string, number> = {};
for (const [chars, width] of GLYPH_GROUPS) {
  for (const ch of chars) GLYPH[ch] = width;
}

/** Незнакомый символ (латиница с диакритикой, редкая пунктуация) — по средней букве. */
const UNKNOWN_GLYPH = 0.6;

/** `letter-spacing: 0.01em` из .chordsheet добавляется к каждому символу — и в тексте, и в аккорде. */
const LETTER_SPACING = 0.01;

/** Полужирное имя аккорда шире обычного текста примерно на два процента. */
const BOLD_RATIO = 1.02;

/** Просвет между соседними аккордами, в долях кегля текста. */
const CHORD_GAP = 0.25;

/**
 * Дефолт `--sheet-chord-size` из .cs-chord — держать в паре с CSS.
 * Само значение подставляет браузер (превью редактора поднимает его до 0.9em),
 * поэтому в отступ оно уходит переменной, а не числом.
 */
const CHORD_SIZE_FALLBACK = '0.72em';

/**
 * Верхняя граница кегля аккорда, при которой отступ ещё может понадобиться.
 * Ниже неё calc() всё пересчитает сам; выше — аккорды крупнее текста, такого в
 * стилях нет.
 */
const MAX_CHORD_SIZE = 1;

/** Ширина текста в долях кегля — с учётом letter-spacing. */
export function textWidthEm(text: string): number {
  let width = 0;
  for (const ch of text) width += (GLYPH[ch] ?? UNKNOWN_GLYPH) + LETTER_SPACING;
  return width;
}

/** Ширина имени аккорда в долях ЕГО кегля, без letter-spacing (он от кегля текста). */
function chordGlyphsEm(chord: string): number {
  let width = 0;
  for (const ch of chord) width += (GLYPH[ch] ?? UNKNOWN_GLYPH) * BOLD_RATIO;
  return width;
}

const round = (n: number): number => Math.round(n * 1000) / 1000;

/**
 * Отступ справа для каждой колонки строки (индексы совпадают с `columns`),
 * `undefined` — если раздвигать нечего.
 *
 * Возвращается CSS-выражение, а не число: ширина аккорда зависит от
 * `--sheet-chord-size`, который задаётся стилями (0.72em на странице песни,
 * 0.9em в превью редактора). Число в em дало бы верный отступ только для
 * одного из них, а `calc()` считается уже с фактическим кеглем.
 */
export function chordPads(columns: Column[]): (string | undefined)[] {
  const pads: (string | undefined)[] = new Array(columns.length).fill(undefined);

  // Ширина колонки = её текст (пустая колонка рисуется пробелом, см. ChordSheet)
  // плюс пробел-разделитель до следующей колонки.
  const widths = columns.map(
    (col) => textWidthEm(col.text || ' ') + (col.spaceAfter ? textWidthEm(' ') : 0),
  );

  for (let i = 0; i < columns.length; i++) {
    const chord = columns[i].chord;
    if (!chord) continue;

    // Докуда аккорду свободно: до следующего аккорда либо до конца строки.
    let next = i + 1;
    while (next < columns.length && !columns[next].chord) next++;
    const toLineEnd = next >= columns.length;

    let available = 0;
    for (let k = i; k < next; k++) available += widths[k];

    // Полдела делает CSS: `glyphs * кегль + slack`. В slack сложены доли,
    // считанные от кегля текста, — они от размера аккорда не зависят.
    const glyphs = chordGlyphsEm(chord);
    const slack =
      [...chord].length * LETTER_SPACING + (toLineEnd ? 0 : CHORD_GAP) - available;
    if (glyphs * MAX_CHORD_SIZE + slack <= 0) continue;

    // Место добавляем в пробел перед следующим аккордом — так слова остаются
    // при своих аккордах, а дыра появляется ровно там, где она вынужденная.
    // Внутри слова (аккорд на середине слова) пробела нет: тогда отступ идёт
    // последней колонке, иначе аккорды наложатся друг на друга.
    // В конце строки двигать нечего — отступ держит вылет имени за последнее
    // слово, чтобы аккорд не оказался за краем колонки.
    let target = next - 1;
    if (!toLineEnd) {
      for (let k = next - 1; k >= i; k--) {
        if (columns[k].spaceAfter) {
          target = k;
          break;
        }
      }
    }

    const sign = slack < 0 ? '-' : '+';
    pads[target] =
      `max(0em, calc(${round(glyphs)} * var(--sheet-chord-size, ${CHORD_SIZE_FALLBACK}) ${sign} ${round(Math.abs(slack))}em))`;
  }

  return pads;
}
