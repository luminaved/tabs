import { describe, expect, it } from 'vitest';
import { plainToChordPro } from './plainImport';

/**
 * Пример-подсказка из диалога импорта (components/ImportTextDialog.tsx).
 * Проверяем, что он действительно показывает то, что обещает: аккорды из
 * строки над словами встают ровно на начала слов. Пример правился вручную по
 * колонкам, и такую разметку легко сдвинуть на символ, сам того не заметив.
 */
const EXAMPLE = `Am      F              C                    G
Простая строчка, чтобы стало видно, как это работает`;

describe('пример в диалоге импорта', () => {
  it('аккорды встают на начала нужных слов', () => {
    expect(plainToChordPro(EXAMPLE)).toBe(
      '[Am]Простая [F]строчка, чтобы [C]стало видно, как это [G]работает',
    );
  });
});
