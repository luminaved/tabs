import { unstable_cache } from 'next/cache';

/**
 * Кэш публичных чтений между запросами.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 *
 * Каждая страница сайта динамическая, и не по недосмотру: шапка и нижняя
 * навигация спрашивают сессию (`auth()` читает cookie), а чтение cookie делает
 * динамическим всё дерево под собой. Значит, ответы нельзя закэшировать
 * целиком — ни в браузере, ни на CDN: они уходят с `no-store`.
 *
 * Но содержимое-то у них общее. Каталог, страница разбора, страница
 * исполнителя — одни и те же строки для всех гостей и всех поисковых роботов,
 * а пересчитывались они на каждый запрос: два-три обращения к базе, которая
 * живёт в другом полушарии (замерено: 33 мс на пустой round-trip, 76–82 мс на
 * запрос каталога, 320 мс на холодном соединении).
 *
 * Поэтому кэшируется не страница, а слой данных. Страница остаётся
 * динамической и честно знает про сессию, но база уходит с критического пути:
 * первый посетитель после протухания платит за запрос, остальные — нет.
 *
 * ── Что НЕ кэшируется ───────────────────────────────────────────────────────
 *
 * Всё, что зависит от того, кто смотрит: своя библиотека, избранное, лайкнутое,
 * состояние лайка на странице разбора. Такое кэшировать пришлось бы ключом с
 * идентификатором пользователя, а это не кэш, а утечка, ждущая ошибки в ключе.
 *
 * Поиск тоже не кэшируется, и это отдельное решение: `q` задаёт посетитель, и
 * кэш по нему — это неограниченное множество ключей, которое любой обход
 * набьёт мусором за минуту. Запрос с поиском идёт в базу напрямую.
 */

/**
 * Срок годности. Минута — компромисс: счётчик просмотров и число лайков в
 * каталоге отстают ровно на неё, зато база не видит основной поток вовсе.
 * Правки самих разборов ждать минуту не должны — их сбрасывает тег (ниже).
 */
export const PUBLIC_TTL = 60;

/**
 * Тег всех публичных списков. Сбрасывается при создании, правке и удалении
 * разбора — то есть там, где страница и так перерисовывается после redirect'а.
 *
 * ВАЖНО: не вызывайте `revalidateTag` в переключателях лайка, избранного и
 * подтверждения. Любая ревалидация внутри серверного экшена заставляет роутер
 * перерисовать текущий маршрут, а вместе с ним слетают транспонирование,
 * размер шрифта и позиция прокрутки читалки — ровно то, ради чего в этих
 * экшенах изначально нет `revalidatePath` (см. songs/engagement-actions.ts).
 * Их изменения догоняет `PUBLIC_TTL`.
 */
export const SONGS_TAG = 'songs';

/** Тег одного разбора — чтобы правка не сбрасывала весь каталог. */
export const songTag = (id: string) => `song:${id}`;

/**
 * `unstable_cache` с тегами, зависящими от аргументов.
 *
 * Штатный `unstable_cache` принимает теги статическим списком, а нам нужен тег
 * с идентификатором разбора. Обёртка создаётся на каждый вызов — это дёшево
 * (замыкание), а ключ кэша всё равно определяется `keyParts`, а не тем, сколько
 * раз мы обернули функцию.
 */
export function cachedByKey<T>(
  keyParts: string[],
  tags: string[],
  fn: () => Promise<T>,
  revalidate: number = PUBLIC_TTL,
): Promise<T> {
  return unstable_cache(fn, keyParts, { tags, revalidate })();
}

/**
 * Оживляет даты после кэша.
 *
 * `unstable_cache` складывает значение через `JSON.stringify` (см. его
 * исходники), поэтому `Date` возвращается СТРОКОЙ, хотя тип из Prisma
 * по-прежнему обещает `Date`. Тихое расхождение: `coverSrc` со строкой
 * работает (он всё равно делает `new Date(...)`), а `song.createdAt
 * .toISOString()` на странице разбора падает.
 *
 * Поэтому поля перечисляются явно, а не угадываются по виду значения: строка,
 * похожая на дату, может оказаться названием песни.
 */
export function reviveDates<T extends object, K extends keyof T>(
  row: T,
  fields: readonly K[],
): T {
  for (const field of fields) {
    const value = row[field];
    if (typeof value === 'string') {
      (row as Record<K, unknown>)[field] = new Date(value);
    }
  }
  return row;
}
