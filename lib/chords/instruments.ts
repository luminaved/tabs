// Барре-формы E-типа: корень на 6-й струне (открытая E, pc 4).
const GUITAR_MOVABLE: Record<string, (f: number) => ChordFrets> = {
  '': (f) => [f, f + 2, f + 2, f + 1, f, f],
  m: (f) => [f, f + 2, f + 2, f, f, f],
  '7': (f) => [f, f + 2, f, f + 1, f, f],
  m7: (f) => [f, f + 2, f, f, f, f],
  maj7: (f) => [f, f + 2, f + 1, f + 1, f, f],
};

/**
 * Квинта на гитаре по высоте корня — то, чем рисуются «A5», «C5», «F#5».
 *
 * Струну корня выбираем так, как её берут в руки: до пятого лада — шестая
 * струна, дальше — пятая. Выше пятого лада форма от шестой струны уводит руку
 * в неудобную позицию, и гитаристы там переходят на струну тоньше.
 *
 * Порог именно 5, а не 7: на A5 обе позиции равноценны (5 лад шестой струны
 * либо открытая пятая), и выбран первый — он звучит полнее. Побочный, но
 * важный эффект: правило один в один воспроизводит прежнюю запись «лад + В/Н»
 * для всех ходовых позиций, поэтому переименование старых разборов не меняет
 * им картинки (закреплено таблицей в тестах).
 *
 * Баррэ не задаётся: квинту берут пальцами 1-3-4, а не поперечным.
 */
/**
 * До какого лада включительно квинта берётся от ШЕСТОЙ струны; выше — от пятой.
 *
 * Числом здесь стояла пятёрка, и её же приходилось знать обратному переводу
 * «G#5» → «4В» (см. `chordNameToPowerFifth` в diagrams.ts): буква В или Н —
 * это ровно ответ на вопрос «на какой струне корень». Разойдись два места — и
 * подпись сказала бы «В» там, где нарисована форма от пятой струны. Поэтому
 * порог живёт в одном экземпляре и импортируется.
 */
export const GUITAR_FIFTH_ON_SIXTH_MAX = 5;

function guitarPowerChord(rootPc: number): ChordShape {
  const sixth = mod12(rootPc - GUITAR_OPEN_PCS[0]);
  if (sixth <= GUITAR_FIFTH_ON_SIXTH_MAX) {
    return { frets: [sixth, sixth + 2, sixth + 2, -1, -1, -1] };
  }
  const fifth = mod12(rootPc - GUITAR_OPEN_PCS[1]);
  return { frets: [-1, fifth, fifth + 2, fifth + 2, -1, -1] };
}

