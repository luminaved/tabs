/**
 * Квинты на укулеле — таблицей позиций, а не одной подвижной формой.
 *
 * На гитаре квинта — это одна форма, которую двигают по грифу, и двух опорных
 * струн хватает на все двенадцать корней. На четырёх струнах так не выходит:
 * строй GCEA не только короче, но и «возвратный» (4-я струна звучит выше 3-й),
 * поэтому корень с квинтой ложатся на разные пары струн в зависимости от
 * высоты, и одна подвижная форма к седьмому корню уезжает к двенадцатому ладу.
 *
 * Каждая строка — самая низкая позиция, где квинта берётся рукой (размах не
 * больше четырёх ладов) и звучит как можно бо́льшим числом струн: укулеле бьют
 * боем по всем четырём, и форма из двух струн на нём звучит пусто. Отсюда три
 * семьи форм подряд:
 *
 *   C…D# — корень на 2-й струне (C), баррэ и две струны сверху;
 *   E…G# — корень на 3-й струне (E);
 *   A…B  — корень на 4-й струне (G), 2-я заглушена (иначе размах в пять ладов).
 *
 * Формы не сочинены за столом: девять из двенадцати ровно те, что были
 * нарисованы руками в уже сохранённых разборах для укулеле, — таблица просто
 * снимает эту работу с человека и, главное, даёт квинте форму на КАЖДОЙ высоте,
 * чтобы при смене тональности картинка не пропадала. Тест проверяет каждую
 * строку на слух (звучат только корень и квинта) и на размах.
 */
const UKULELE_POWER: ChordShape[] = [
  { frets: [0, 0, 3, 3] }, // C5
  { frets: [1, 1, 4, 4], barres: [{ fret: 1, from: 0, to: 3 }] }, // C#5
  { frets: [2, 2, 5, 5], barres: [{ fret: 2, from: 0, to: 3 }] }, // D5
  { frets: [3, 3, 6, 6], barres: [{ fret: 3, from: 0, to: 3 }] }, // D#5
  { frets: [4, 4, 0, 2] }, // E5
  { frets: [-1, 0, 1, 3] }, // F5
  { frets: [-1, 1, 2, 4] }, // F#5
  { frets: [0, 2, 3, 5] }, // G5
  { frets: [-1, 3, 4, 6] }, // G#5
  { frets: [2, 4, 0, 0] }, // A5
  { frets: [3, -1, 1, 1], barres: [{ fret: 1, from: 2, to: 3 }] }, // A#5
  { frets: [4, -1, 2, 2], barres: [{ fret: 2, from: 2, to: 3 }] }, // B5
];

