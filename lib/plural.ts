/**
 * Русское склонение существительного при числительном.
 *
 * Правило одно на весь проект: до этого оно было выписано трижды (черновики,
 * подпись числа струн, счётчик разборов у исполнителя), и на странице
 * исполнителя копия была неверной — там форма выбиралась по `n < 5`, из-за чего
 * получалось «21 разборов» вместо «21 разбор» и «22 разборов» вместо «22
 * разбора». Развилка идёт по последней цифре, но десятки 11–14 — исключение:
 * они всегда берут форму множественного числа.
 */
export function pluralRu(n: number, one: string, few: string, many: string): string {
  const abs = Math.abs(Math.trunc(n));
  const mod10 = abs % 10;
  const mod100 = abs % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}

/** «1 разбор» / «2 разбора» / «5 разборов» — число вместе с формой слова. */
export function withPluralRu(
  n: number,
  one: string,
  few: string,
  many: string,
): string {
  return `${n} ${pluralRu(n, one, few, many)}`;
}

/**
 * Короткая запись большого числа: 999 → «999», 1234 → «1,2 тыс.», 3e6 → «3 млн».
 *
 * Своя, а не `Intl.NumberFormat` с `notation: 'compact'`: тот зависит от полноты
 * ICU в сборке Node, а расходиться в числах между машиной разработчика и
 * сервером счётчику нельзя. Заодно правило видно глазами и покрыто тестами.
 *
 * Дробь ОТБРАСЫВАЕТСЯ, а не округляется. Счётчик, показывающий больше, чем
 * есть, — это «1,3 тыс. просмотров» при 1250: округление вверх здесь врёт в
 * пользу сайта, и лучше пусть цифра будет скромнее правды, чем наоборот.
 * Побочно это чинит и край диапазона: округление превратило бы 999 999 в
 * «1000 тыс.» вместо «999 тыс.».
 */
export function compactRu(n: number): string {
  const abs = Math.abs(Math.trunc(n));
  const sign = n < 0 ? '-' : '';
  if (abs < 1000) return sign + String(abs);

  const [div, unit] = abs < 1_000_000 ? [1000, 'тыс.'] : [1_000_000, 'млн'];
  const value = abs / div;
  // До десяти — с одним знаком после запятой: разница между 1,2 и 1,9 тыс.
  // заметна, а между 123,4 и 123,9 тыс. — уже нет, там дробь только шумит.
  const shown = value < 10 ? Math.floor(value * 10) / 10 : Math.floor(value);
  return `${sign}${String(shown).replace('.', ',')} ${unit}`;
}
