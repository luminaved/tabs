/**
 * Адреса каталога с текущими параметрами отбора.
 *
 * Поиск, сортировка и «только подтверждённые» живут в строке запроса, а сами
 * переключатели остаются ссылками: работают без JS, индексируются и ими можно
 * поделиться. Отсюда требование — каждый переключатель обязан сохранять
 * ОСТАЛЬНЫЕ параметры. Раньше строка собиралась в каждом из них отдельно, и
 * новый отбор пришлось бы не забыть в трёх местах; теперь место одно.
 *
 * Значения по умолчанию в адрес не пишем: базовый каталог остаётся на чистом
 * `/`, и canonical не расходится с реальной ссылкой.
 */

import { parsePage } from './paging';

/** Порядок в каталоге: новые / популярные (просмотры) / любимые (лайки). */
export type SongSort = 'new' | 'views' | 'likes';

/** Порядок по умолчанию. В адрес не пишется — см. `catalogHref`. */
export const DEFAULT_SORT: SongSort = 'new';

/**
 * Приводит значение из query-параметра к допустимой сортировке.
 *
 * Живёт ЗДЕСЬ, а не в lib/songs.ts, где было раньше: тот модуль тянет за собой
 * Prisma, а разбор параметра нужен и метаданным (lib/seo.ts), которым клиент
 * базы ни к чему. Заодно `isDefaultSort` и `catalogHref` теперь считают
 * значение по умолчанию одним и тем же кодом и не могут разойтись.
 */
export function parseSort(value: string | undefined | null): SongSort {
  return value === 'views' || value === 'likes' ? value : DEFAULT_SORT;
}

/**
 * Задаёт ли параметр сортировку, ОТЛИЧНУЮ от порядка по умолчанию.
 *
 * Нужен метаданным каталога. Там стояла проверка на само наличие параметра, и
 * из-за неё адрес `/?sort=new` — та же самая выдача, что и чистый каталог —
 * объявлялся отобранным и получал `noindex`. Внутренние ссылки такого адреса
 * не собирают, но по внешней ссылке или из закладки на него попасть можно, и
 * главная страница молча уходила из индекса.
 */
export function isDefaultSort(value: string | undefined | null): boolean {
  return parseSort(value) === DEFAULT_SORT;
}

export interface CatalogParams {
  /** Поисковый запрос. */
  query?: string;
  /** Сортировка; `new` — по умолчанию и в адрес не попадает. */
  sort?: string;
  /** Только подтверждённые модератором разборы. */
  verified?: boolean;
  /**
   * Номер страницы, СЧИТАЯ С ЕДИНИЦЫ — как его видит человек в адресе.
   * Внутри (`listPublicSongs`, экшены) страницы нумеруются с нуля, поэтому на
   * границе всегда есть ±1; здесь единица выбрана потому, что адрес читают
   * люди, а «page=0» для второй страницы объяснить невозможно.
   *
   * Первая страница в адрес НЕ пишется: у каталога должен остаться ровно один
   * адрес, иначе `/` и `/?page=1` — две копии одной выдачи.
   */
  page?: number;
}

export function catalogHref(basePath: string, params: CatalogParams = {}): string {
  const qs = new URLSearchParams();
  if (params.query) qs.set('q', params.query);
  if (params.sort && !isDefaultSort(params.sort)) qs.set('sort', params.sort);
  if (params.verified) qs.set('verified', '1');
  if (params.page && params.page > 1) qs.set('page', String(params.page));
  const s = qs.toString();
  return s ? `${basePath}?${s}` : basePath;
}

/**
 * Номер страницы из адреса — с единицы, с тем же потолком, что и у выборки из
 * БД: `parsePage` не пускает дальше, чтобы запросом нельзя было заставить
 * Postgres пролистать и выбросить произвольно много строк.
 *
 * Мусор («abc», отрицательное, дробное) молча становится первой страницей:
 * номер приходит из адреса, то есть от кого угодно, и падать на нём незачем.
 */
export function parseCatalogPage(value: string | undefined | null): number {
  return Math.max(1, parsePage(value));
}

/**
 * Значение отбора «только подтверждённые» из адреса, формы или экшена.
 * Всё, кроме явной единицы, считаем выключенным — отбор включает пользователь,
 * и случайный мусор в параметре не должен молча резать выдачу.
 */
export function parseVerifiedParam(value: string | undefined | null): boolean {
  return value === '1';
}
