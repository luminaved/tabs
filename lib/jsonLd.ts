/**
 * Сериализация структурированных данных для вставки в <script type="application/ld+json">.
 *
 * Голый `JSON.stringify` сюда не годится: он экранирует кавычки и переводы
 * строк, но не `<` и `>`. Название разбора — свободное поле, и строка
 * `</script>` внутри него закрывает тег раньше времени, а всё, что после,
 * браузер разбирает уже как разметку. Публичная страница разбора индексируется
 * и открыта всем, поэтому это прямая дыра, а не теоретическая.
 *
 * Экранируем через \uXXXX: внутри JSON-строки это тот же символ, поисковик
 * читает разметку без изменений, а HTML-парсер тега больше не видит.
 * U+2028/U+2029 — валидный JSON, но не валидный JS-литерал; экранированы на
 * случай, если разметку когда-нибудь начнут разбирать как скрипт.
 *
 * В самих регулярках только ASCII-escape'ы: сырые U+2028/U+2029 в исходнике
 * невидимы и легко теряются при копировании файла.
 */
export function jsonLdScript(data: unknown): string {
  return JSON.stringify(data)
    .replace(/</g, '\\u003c')
    .replace(/>/g, '\\u003e')
    .replace(/&/g, '\\u0026')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
}
