/**
 * Ссылка на загруженный аватар. Как и обложка, он отдаётся отдельным маршрутом
 * (`/avatars/[id]`), а не вшивается base64 в разметку каждой страницы.
 *
 * Ссылка версионируется отпечатком самой картинки. Без версии маршрут держал
 * пережатый аватар в кэше процесса по ключу «id + формат», и после смены фото
 * пользователь продолжал видеть старое, пока сервер не перезапустят: в БД лежит
 * новая картинка, а промаха кэша не происходит. Теперь смена фото меняет `v` —
 * значит и ключ кэша, и адрес для браузера.
 */

/**
 * Дешёвый отпечаток data URL. Криптостойкость не нужна — нужно лишь, чтобы
 * ссылка менялась вместе с картинкой. Хешируем длину и хвост: аватар весит
 * десятки килобайт, а шапка рисуется на каждой странице, и прогонять всю строку
 * ради версии незачем. Две разные картинки одинаковой длины с одинаковыми
 * последними байтами практически не встречаются.
 */
function fingerprint(dataUrl: string): string {
  const tail = dataUrl.slice(-128);
  let h = dataUrl.length;
  for (let i = 0; i < tail.length; i++) h = (Math.imul(31, h) + tail.charCodeAt(i)) | 0;
  return (h >>> 0).toString(36);
}

/** Загруженный аватар (data URL) — ссылкой; внешний (Google) — как есть. */
export function avatarSrc(userId: string, image: string): string {
  if (!image.startsWith('data:')) return image;
  return `/avatars/${userId}?v=${fingerprint(image)}`;
}
