/**
 * Ссылка на загруженный аватар. Как и обложка, он отдаётся отдельным маршрутом
 * (`/avatars/[id]`), а не вшивается base64 в разметку каждой страницы.
 *
 * Ссылка версионируется отпечатком самой картинки. Без версии маршрут держал
 * пережатый аватар в кэше процесса по ключу «id + формат», и после смены фото
 * пользователь продолжал видеть старое, пока сервер не перезапустят: в БД лежит
 * новая картинка, а промаха кэша не происходит. Теперь смена фото меняет `v` —
 * значит и ключ кэша, и адрес для браузера.
 */

/**
 * Сколько последних символов участвует в отпечатке. Экспортируется, потому что
 * ровно это число подставляется в `right(image, N)` при выборке из БД
 * (см. lib/users.ts) — разъехавшись, они дали бы разные версии для одной и той
 * же картинки, и браузер перестал бы попадать в кэш.
 */
export const AVATAR_TAIL_CHARS = 128;

/**
 * Отпечаток по длине и хвосту картинки.
 *
 * Отдельно от `avatarVersion` он нужен затем, что шапка (а она есть на каждой
 * странице) саму картинку из базы больше не тянет: ей достаточно `length(image)`
 * и `right(image, 128)` — полторы сотни байт вместо всего data URL. Обе функции
 * обязаны давать одинаковый результат, это закреплено тестом.
 */
export function avatarVersionFromParts(length: number, tail: string): string {
  let h = length;
  for (let i = 0; i < tail.length; i++) h = (Math.imul(31, h) + tail.charCodeAt(i)) | 0;
  return (h >>> 0).toString(36);
}

/**
 * Дешёвый отпечаток data URL — для тех, у кого картинка уже на руках (сам
 * маршрут /avatars/[id]). Криптостойкость не нужна: нужно лишь, чтобы ссылка
 * менялась вместе с картинкой. Две разные картинки одинаковой длины с
 * одинаковыми последними байтами практически не встречаются.
 */
export function avatarVersion(dataUrl: string): string {
  return avatarVersionFromParts(dataUrl.length, dataUrl.slice(-AVATAR_TAIL_CHARS));
}

/**
 * Ссылка на аватар — ВСЕГДА через свой маршрут, и для загруженного фото, и для
 * картинки Google.
 *
 * Раньше внешний адрес отдавался как есть, и браузер посетителя шёл за
 * картинкой на googleusercontent.com. Это был единственный сторонний хост на
 * всём сайте: там, где Google недоступен или режется, аватары просто не
 * грузились, а заодно чужой сервер видел адреса всех, кто открыл профиль.
 * Теперь наружу ходит сервер (см. app/avatars/[id]/route.ts), а посетитель —
 * только к нам.
 *
 * Принимает готовую версию, а не картинку: вызывающему коду (шапка, профиль)
 * base64 не нужен и в руки не попадает.
 */
export function avatarSrc(userId: string, version: string): string {
  return `/avatars/${userId}?v=${version}`;
}
