/**
 * Читаемая часть адреса разбора: `/songs/17-nozhevyh-cupsize-cmrxly6830002uk40`.
 *
 * Зачем вообще: голый `cuid` ничего не сообщает ни человеку, ни поисковику.
 * В выдаче адрес показывается под заголовком, и «pesnya-ispolnitel» там читается
 * как подтверждение, что страница про ту самую песню, — это и клики, и слабый,
 * но настоящий сигнал релевантности (у Яндекса заметнее, чем у Google).
 *
 * Идентификатор ОСТАЁТСЯ в адресе и остаётся первичным ключом: подпись — только
 * украшение. Поэтому переименование песни не ломает ссылки (старый адрес ведёт
 * на тот же разбор и получает 308 на новый), а совпадение названий у двух песен
 * не создаёт конфликта. Хранить slug в базе и следить за его уникальностью —
 * ровно та работа, которой эта схема позволяет не заниматься.
 */

/**
 * Кириллица → латиница. Схема «как читается», а не ГОСТ: адрес пишется для
 * человека. Украинские і/ї/є/ґ добавлены не про запас — их регулярно приносят
 * названия песен, а без них буква просто выпала бы из подписи.
 */
const TRANSLIT: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z',
  и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r',
  с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'c', ч: 'ch', ш: 'sh', щ: 'sch',
  ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
  і: 'i', ї: 'yi', є: 'ye', ґ: 'g', ў: 'u',
};

/**
 * Потолок длины подписи. Ограничение не техническое (адреса бывают длиннее), а
 * практическое: в выдаче адрес обрезается, и хвост из десятого слова названия
 * пользы не приносит, зато мешает читать. Режем по границе слова.
 */
const MAX_SLUG = 60;

/**
 * Строка → часть адреса: строчные латинские буквы, цифры и дефисы.
 *
 * `normalize('NFKD')` + срез диакритики нужен для латиницы с надстрочными
 * знаками (é → e): без него «é» не попала бы ни в один разрешённый класс и
 * превратилась бы в дефис, разорвав слово.
 */
export function slugify(text: string): string {
  const out = text
    .toLowerCase()
    .normalize('NFKD')
    // Диакритика (комбинирующие знаки) после NFKD стоит отдельными символами.
    // `\p{M}` вместо диапазона кодов: сами эти символы в исходнике невидимы и
    // теряются при копировании файла, а именованный класс читается и не портится.
    .replace(/\p{M}/gu, '')
    .replace(/[а-яёіїєґў]/g, (ch) => TRANSLIT[ch] ?? '')
    // Всё, что не буква и не цифра, — разделитель. Скобки, кавычки, точки и
    // эмодзи из названий песен попадают сюда же.
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

  if (out.length <= MAX_SLUG) return out;
  const cut = out.slice(0, MAX_SLUG);
  // Обрезали посреди слова — откатываемся к последнему дефису, чтобы в адресе
  // не оставалось обрубка вроде «transponirovan».
  const lastDash = cut.lastIndexOf('-');
  return (lastDash > 0 ? cut.slice(0, lastDash) : cut).replace(/-+$/, '');
}

/** Поля, из которых собирается подпись. Структурный тип: подходит и строке
 *  каталога, и записи из БД — лишь бы были название с исполнителем. */
export interface SongPathFields {
  id: string;
  title: string;
  artist?: string | null;
}

/**
 * Канонический адрес разбора.
 *
 * Название идёт ПЕРЕД исполнителем: ищут чаще по песне, а начало адреса и
 * заметнее, и переживает обрезку в выдаче. Если от названия с исполнителем не
 * осталось ни одного латинского символа (название из одних символов или,
 * скажем, иероглифов), подписи просто не будет — адрес выродится в прежний
 * `/songs/<id>`, который продолжает работать.
 */
export function songPath(song: SongPathFields): string {
  const slug = slugify([song.title, song.artist].filter(Boolean).join(' '));
  return slug ? `/songs/${slug}-${song.id}` : `/songs/${song.id}`;
}

/**
 * Обратная операция: из сегмента адреса достать идентификатор.
 *
 * Держится на том, что `cuid()` у Prisma — это строчные буквы и цифры без
 * дефисов. Значит идентификатор всегда лежит после ПОСЛЕДНЕГО дефиса, а всё до
 * него — подпись, какой бы она ни была. Голый `/songs/<id>` (адрес, который
 * сайт раздавал раньше) проходит через ту же функцию без изменений.
 */
export function songIdFromParam(param: string): string {
  const decoded = safeDecode(param);
  const cut = decoded.lastIndexOf('-');
  return cut === -1 ? decoded : decoded.slice(cut + 1);
}

/** Сегмент адреса приезжает закодированным, если в подписи оказалась не-латиница. */
function safeDecode(value: string): string {
  try {
    return decodeURIComponent(value);
  } catch {
    return value;
  }
}
