/**
 * Контакт для обращений правообладателей.
 *
 * Зачем отдельным модулем: адрес нужен трём местам сразу — странице
 * «Правообладателям», подвалу и админской проверке «а настроено ли вообще», —
 * и все трое обязаны видеть одно и то же значение.
 *
 * Живёт в переменной окружения, а не строкой в коде, по тому же правилу, что и
 * коды вебмастера (см. .env.example): адрес привязан к конкретному владельцу
 * сайта, и в общем репозитории ему не место. Плюс адрес в публичном репозитории
 * собирают спам-роботы ещё до того, как его увидит первый правообладатель.
 *
 * ВНИМАНИЕ: модуль читает `process.env` без префикса NEXT_PUBLIC_, поэтому
 * импортировать его можно ТОЛЬКО из серверных компонентов. В клиентском бандле
 * значение окажется пустым — и страница молча перестанет показывать контакт.
 */

import { validateEmail } from './validation';

/**
 * Проверенный адрес либо null.
 *
 * Проверка не формальность: опечатка в переменной окружения даёт страницу с
 * неработающей ссылкой `mailto:`, а заметить это некому — владелец сайта себе
 * жалобу не пишет. Пустое значение честнее битого: страница тогда прямо
 * говорит, что связаться пока нельзя, а админка это подсвечивает.
 */
export function parseContactEmail(raw: string | undefined | null): string | null {
  const value = raw?.trim();
  if (!value) return null;
  return validateEmail(value) ? value : null;
}

/** Адрес для обращений правообладателей. null — переменная не задана. */
export const COPYRIGHT_EMAIL = parseContactEmail(process.env.COPYRIGHT_EMAIL);

/**
 * Ссылка `mailto:` с готовой темой и, если известен, адресом страницы в теле
 * письма. Тема — чтобы обращение не потерялось среди прочей почты; адрес
 * страницы — потому что обращение без точного URL это первая причина
 * уточняющей переписки, а она стоит суток сверху к сроку удаления.
 *
 * Кодируем `encodeURIComponent`, а НЕ `URLSearchParams`, и это не вкусовщина:
 * `URLSearchParams` кодирует по правилам HTML-формы и превращает пробел в `+`.
 * В `mailto:` (RFC 6068) плюс — обычный символ, а не пробел, поэтому почтовый
 * клиент показал бы тему «Обращение+правообладателя». Процентное кодирование
 * понимают оба.
 */
export function copyrightMailto(email: string, pageUrl?: string): string {
  const params = [`subject=${encodeURIComponent('Обращение правообладателя')}`];
  if (pageUrl) params.push(`body=${encodeURIComponent(`Страница: ${pageUrl}\n\n`)}`);
  return `mailto:${email}?${params.join('&')}`;
}
