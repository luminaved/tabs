/**
 * Экранирование для XML.
 *
 * Живёт отдельным модулем, потому что нужен обоим машинным файлам сайта — ленте
 * (app/feed.xml) и карте (app/sitemap.xml). Оба собираются подстановкой строк,
 * а XML разбирается строго: один сырой амперсанд в названии песни ломает не
 * строчку, а весь документ — читалка или поисковик отбрасывают его целиком.
 *
 * Апостроф и кавычка экранируются не «на всякий случай»: те же строки
 * подставляются и в атрибуты (`href` в ленте).
 */
export function xmlEscape(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}
