/**
 * Сборка структурированных данных (schema.org) — того, что уходит в
 * `<script type="application/ld+json">`.
 *
 * Живёт отдельным модулем, потому что одни и те же куски нужны разным
 * страницам: издателя просит разметка разбора, «хлебные крошки» — и разбор, и
 * исполнитель, список — и каталог, и профиль автора. Разъехавшиеся копии здесь
 * не просто некрасивы: поисковик сверяет разметку разных страниц между собой, и
 * сайт, называющий себя то так, то иначе, теряет право на расширенную выдачу.
 *
 * Сериализация — в [jsonLd.ts](./jsonLd.ts): там же объяснено, почему голого
 * JSON.stringify недостаточно.
 */

import { absoluteUrl, SITE_NAME, SITE_TAGLINE, SITE_URL } from './site';
import { catalogHref, parseCatalogPage } from './catalogUrl';
import type { Instrument } from './chords/instruments';

/**
 * Издатель. `@id` даёт постоянный якорь: разметка разбора ссылается на него
 * вместо того, чтобы повторять описание организации на каждой странице.
 */
export const publisherJsonLd = {
  '@type': 'Organization',
  '@id': `${SITE_URL}/#org`,
  name: SITE_NAME,
  url: SITE_URL,
  logo: absoluteUrl('/icon.svg'),
} as const;

/**
 * Разметка сайта для главной. Именно по ней Google решает, каким именем
 * подписать сайт в выдаче.
 *
 * `potentialAction` — заявка на строку поиска прямо в выдаче (sitelinks
 * searchbox). Адрес должен вести на РАБОТАЮЩИЙ поиск: у нас это каталог с
 * `?q=` — тот же параметр, что заполняет форма на странице.
 */
export const websiteJsonLd = {
  '@context': 'https://schema.org',
  '@type': 'WebSite',
  '@id': `${SITE_URL}/#website`,
  name: SITE_NAME,
  description: SITE_TAGLINE,
  url: SITE_URL,
  inLanguage: 'ru',
  publisher: publisherJsonLd,
  potentialAction: {
    '@type': 'SearchAction',
    target: {
      '@type': 'EntryPoint',
      urlTemplate: `${SITE_URL}/?q={search_term_string}`,
    },
    'query-input': 'required name=search_term_string',
  },
};

/**
 * Заголовок страницы разбора — он же подпись к ссылке при «Поделиться».
 *
 * Формула собрана под живые запросы, а не под красоту. Люди ищут тремя
 * способами: «<песня> аккорды», «<исполнитель> <песня> аккорды» и «разбор
 * песни <песня>». Поэтому в заголовке стоят и «аккорды», и «разбор», и оба
 * имени — а название идёт первым, потому что в выдаче заголовок обрезается
 * примерно на шестидесяти знаках, и уцелеть должно именно оно.
 *
 * «на гитаре»/«на укулеле» — не украшение: каталоги разделены по инструментам
 * (см. [instruments.ts](./chords/instruments.ts)), и запрос «аккорды на
 * укулеле» должен приводить на укулельный разбор, а не на гитарный.
 */
export function songSeoTitle(
  song: { title: string; artist?: string | null },
  inst: Instrument,
): string {
  const artist = song.artist?.trim();
  return artist
    ? `${song.title} — ${artist}: аккорды и разбор на ${inst.onName}`
    : `${song.title} — аккорды и разбор на ${inst.onName}`;
}

/**
 * Описание для выдачи и превью ссылки.
 *
 * Здесь намеренно перечислено то, чем страница отличается от сотни таких же:
 * аккорды стоят НАД словами, аппликатуры показываются, тональность меняется.
 * Поисковик описание в ранжировании почти не учитывает — а вот человек в
 * выдаче читает именно его и по нему решает, кликать ли.
 */
export function songSeoDescription(
  song: { title: string; artist?: string | null; key?: string | null },
  inst: Instrument,
): string {
  const artist = song.artist?.trim();
  return [
    `Разбор песни «${song.title}»${artist ? ` — ${artist}` : ''}:`,
    `текст с аккордами над словами, аппликатуры для ${inst.forName},`,
    'транспонирование в любую тональность и капо.',
    song.key ? `Тональность: ${song.key}.` : '',
  ]
    .filter(Boolean)
    .join(' ');
}

/*
 * Вводного абзаца на самой странице разбора здесь СОЗНАТЕЛЬНО нет.
 *
 * Он был и убран: три строки описания над кнопками ломали шапку ради небольшой
 * прибавки — своего текста на странице и без него достаточно (заголовок,
 * описание в выдаче, исполнитель, крошки, «От автора», заголовки соседних
 * разборов).
 *
 * Прятать такой текст (`sr-only`, `display: none`, нулевая высота) — не
 * компромисс, а cloaking: разное содержимое человеку и роботу. В лучшем случае
 * оно не считается, в худшем это ручные санкции. Если абзац когда-нибудь
 * вернётся — только видимым.
 */

/**
 * Метаданные каталога — общие для гитары и укулеле.
 *
 * Здесь решаются два РАЗНЫХ вопроса, и путать их нельзя:
 *
 * 1. Отбор (`?q=`, `?sort=`, `?verified=`) — страница уходит из индекса, а
 *    canonical указывает на чистый каталог. Иначе одна и та же выдача
 *    расползается по десяткам адресов в любых сочетаниях, обход тратится на
 *    перебор комбинаций вместо самих разборов, а вес делится между копиями.
 *    `follow: true` обязателен: закрываем страницу, а не путь через неё.
 *
 * 2. Пагинация (`?page=`) — наоборот, ОСТАЁТСЯ в индексе, и canonical у неё
 *    свой собственный. Это не копия первой страницы, а другие разборы.
 *    Соблазн написать `canonical: '/'` на всех страницах велик и ошибочен:
 *    поисковик такую подсказку либо игнорирует, либо верит ей — и тогда
 *    перестаёт заходить за первую страницу, то есть глубина каталога выпадает
 *    из индекса целиком. По той же причине здесь нет `noindex` для страниц со
 *    второй: `noindex, follow` со временем начинает работать как
 *    `noindex, nofollow`, и ссылки на разборы вглубь обесцениваются.
 */
export interface CatalogFilters {
  q?: string;
  sort?: string;
  verified?: string;
  page?: string;
}

/**
 * Канонический адрес каталога. Отдельной функцией, потому что его приходится
 * ставить в ДВУХ местах — см. `catalogCanonicalNeedsTag`.
 */
export function catalogCanonical(path: string, filters: CatalogFilters): string {
  const filtered = !!(filters.q?.trim() || filters.sort || filters.verified);
  // Отобранная выдача склеивается с чистым каталогом: она и так не в индексе.
  return filtered ? path : catalogHref(path, { page: parseCatalogPage(filters.page) });
}

/**
 * Сможет ли Next выразить этот canonical без искажения.
 *
 * Баг, проверен на Next 15.5: `resolveAbsoluteUrlWithPathname` заканчивается
 * строкой `result.pathname === '/' ? result.origin : result.href` — у адреса,
 * чей ПУТЬ равен корню, отбрасывается всё, кроме источника, вместе с
 * query-строкой. Каталог гитары и есть корень сайта, поэтому «/?page=2»
 * превращался в голый «https://сайт»: вторая страница объявляла себя копией
 * первой — ровно то, чего пагинация делать не должна, иначе поисковик
 * перестаёт заходить вглубь каталога.
 *
 * Обойти это через `alternates` нельзя: форма с объектом `URL` упирается в ту
 * же строку. Ставить тег руками из разметки тоже нельзя — у каталога есть
 * `loading.tsx`, ответ уходит стримом, и `<head>` улетает раньше, чем
 * отрисуется страница (проверено: тег остаётся в `<body>`, где поисковик его
 * не читает).
 *
 * Поэтому на таких адресах canonical просто НЕ выводится. Это не полумера:
 * тег нужен, только чтобы РАЗЛИЧИТЬ дубли, а когда его нет, поисковик берёт
 * канонической саму запрошенную ссылку — то есть ровно то, что и требуется.
 * Дублей у «/?page=2» нет: на неё не ведёт ни один другой адрес.
 *
 * На «/ukulele?page=2» путь не корневой, тег выводится обычным способом.
 */
export function catalogCanonicalIsSafe(canonical: string): boolean {
  return !canonical.startsWith('/?');
}

export function catalogMetadata(
  inst: Instrument,
  path: string,
  filters: CatalogFilters,
) {
  const filtered = !!(filters.q?.trim() || filters.sort || filters.verified);
  const page = parseCatalogPage(filters.page);
  // Заголовок страницы со второй обязан отличаться: одинаковые заголовки у
  // разных адресов поисковик считает признаком дублей.
  const title =
    page > 1
      ? `Аккорды песен на ${inst.onName} — страница ${page}`
      : `Аккорды песен на ${inst.onName} — тексты с аккордами и разборы`;
  const description =
    `Каталог разборов: аккорды песен для ${inst.forName} с текстом над словами, ` +
    // Строй в описании — не педантизм: «аккорды укулеле GCEA» ищут именно так,
    // а строка собирается из таблицы инструмента и не разойдётся со схемами.
    `аппликатурами под строй ${inst.labels.join('')} и транспонированием. ` +
    'Ищите по названию, строчке из песни или исполнителю.';

  // Свой адрес у каждой страницы пагинации. У отобранной выдачи — чистый
  // каталог: она из индекса и так исключена, и склеивать её надо с ним.
  const canonical = catalogCanonical(path, filters);

  return {
    title,
    description,
    alternates: {
      // Адрес, который Next исказил бы, лучше не объявлять вовсе, чем объявить
      // неправильно: без тега канонической считается сама ссылка (см. выше).
      ...(catalogCanonicalIsSafe(canonical) ? { canonical } : {}),
      // Ссылку на ленту приходится повторять здесь, хотя она есть и в корневом
      // layout: Next не дополняет `alternates` родителя, а ЗАМЕНЯЕТ блок
      // целиком — стоит странице задать свой canonical, и ссылка на ленту с неё
      // пропадает. А ищут её как раз на главной, то есть ровно там, где
      // canonical задан. (Та же ловушка описана у openGraph ниже.)
      types: {
        'application/rss+xml': [{ url: '/feed.xml', title: `${SITE_NAME} — новые разборы` }],
      },
    },
    ...(filtered ? { robots: { index: false, follow: true } } : {}),
    openGraph: {
      type: 'website' as const,
      url: canonical,
      // siteName и locale приходится повторять на каждой странице со своим
      // openGraph: Next заменяет этот блок целиком, а не дополняет корневой, и
      // без них превью ссылки уходит в мессенджер без имени сайта.
      siteName: SITE_NAME,
      locale: 'ru_RU',
      title,
      description,
    },
  };
}

/** Крошка: как называется раздел и куда ведёт. */
export interface Crumb {
  name: string;
  path: string;
}

/**
 * «Хлебные крошки» для выдачи. Google рисует их вместо адреса под заголовком —
 * то есть это не украшение страницы, а то, как ссылка выглядит в поиске.
 *
 * Последняя крошка — сама страница; `item` у неё намеренно есть: спецификация
 * разрешает и опустить, но с адресом разметка проходит проверку без
 * предупреждений в обоих поисковиках.
 */
export function breadcrumbJsonLd(crumbs: Crumb[]) {
  return {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: crumbs.map((c, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      name: c.name,
      item: absoluteUrl(c.path),
    })),
  };
}

/**
 * Список ссылок на странице-перечне (каталог, исполнитель, профиль автора).
 *
 * Даёт поисковику явную связь «эта страница ведёт вот на эти разборы» —
 * страницы-перечни от этого индексируются заметно охотнее, чем когда та же
 * информация есть только в разметке ссылок.
 */
export function itemListJsonLd(items: Crumb[], name: string) {
  return {
    '@context': 'https://schema.org',
    '@type': 'ItemList',
    name,
    numberOfItems: items.length,
    itemListElement: items.map((item, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      name: item.name,
      url: absoluteUrl(item.path),
    })),
  };
}
