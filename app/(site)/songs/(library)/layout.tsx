import { requireUser } from '@/lib/session';

/**
 * Гейт входа для своей библиотеки.
 *
 * Нужен ровно из-за соседнего `loading.tsx`: со скелетоном ответ уходит стримом,
 * а после начала стрима заголовок Location поставить уже нельзя — `redirect` из
 * `requireUser()` внутри страницы выродился бы в переход на стороне клиента,
 * то есть гость успел бы увидеть скелетон чужой библиотеки, прежде чем его
 * унесёт на вход. Layout своей группы рендерится ВЫШЕ Suspense-границы, которую
 * создаёт этот `loading.tsx`, поэтому редирект остаётся честным, HTTP-ным.
 *
 * Почему группа `(library)`, а не сегмент `songs` целиком: `songs/layout.tsx`
 * накрыл бы и `/songs/<id>` — публичные разборы, которые обязаны открываться
 * без входа. Группа в адресе не участвует: страницы по-прежнему обслуживают
 * «/songs» и «/songs/ukulele».
 *
 * Лишнего запроса нет: `requireUser` читает JWT-сессию из cookie, в базу не
 * ходит, а сами страницы вызывают его повторно уже для получения id.
 */
export default async function LibraryLayout({ children }: { children: React.ReactNode }) {
  await requireUser();
  return <>{children}</>;
}
