import type { MetadataRoute } from 'next';
import { SITE_URL } from '@/lib/site';

/**
 * Индексируем каталог, публичные разборы, страницы исполнителей и профили
 * авторов. Личные разделы (кабинет, мои песни, редактор, вход) закрыты — там
 * нет ничего для поиска, а обход только тратит краулинговый бюджет.
 */
export default function robots(): MetadataRoute.Robots {
  return {
    rules: [
      {
        userAgent: '*',
        allow: '/',
        // `/admin` тут намеренно НЕ указан: он отдаёт 404 всем, кроме
        // администратора, поэтому индексировать там нечего и краулинг-бюджет
        // не тратится. Строчка в robots.txt (файл публичный) только сообщила
        // бы адрес всем желающим.
        disallow: [
          '/account',
          // Личная библиотека. `$` здесь обязателен и не является украшением:
          // правила robots.txt сопоставляются по ПРЕФИКСУ, поэтому «/songs»
          // закрыло бы и «/songs/<id>» — то есть все публичные разборы, ради
          // индексации которых сайт и открывали. `$` ограничивает правило
          // ровно этим адресом. Краулеры, не понимающие `$` (это расширение
          // Google и Bing, а не исходный стандарт), просто не найдут пути с
          // таким именем и ничего не закроют — то есть худший случай безвреден.
          '/songs$',
          // Та же библиотека с параметрами: `$` требует КОНЦА адреса, поэтому
          // «/songs$» не закрывает «/songs?q=…», а поиск по своей библиотеке
          // ссылается именно так. Здесь `$` не нужен — это префикс, и под него
          // не подходит ни один публичный разбор (у тех после «/songs» идёт
          // косая черта, а не вопросительный знак).
          '/songs?',
          // Та же личная библиотека, но для укулеле (app/(site)/songs/ukulele).
          // Отдельной строкой, потому что `/songs$` закрывает РОВНО «/songs» —
          // в том и был смысл `$`, — а без неё вход в чужой кабинет оставался
          // открытым для обхода и попадал в выдачу пустой страницей логина.
          '/songs/ukulele$',
          '/songs/ukulele?',
          '/songs/new',
          '/songs/*/edit',
          '/login',
          '/register',
          '/demo',
          '/api/',
        ],
      },
    ],
    // Одна строка на карту. Больше карт здесь не появится «само»: файл
    // sitemap.ts собирает всё из базы (см. комментарий там).
    sitemap: `${SITE_URL}/sitemap.xml`,
    // Директивы `Host` здесь нет намеренно. Её понимал только Яндекс, и он
    // отменил её в 2018 году — зеркала он с тех пор определяет по редиректам, а
    // строку просто игнорирует. Мёртвая настройка хуже отсутствующей: она
    // создаёт впечатление, что главное зеркало где-то задано.
  };
}
