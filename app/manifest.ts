import type { MetadataRoute } from 'next';
import { SITE_NAME, SITE_TAGLINE } from '@/lib/site';

/**
 * Манифест веб-приложения: «Добавить на главный экран».
 *
 * Сценарий у сайта — гитара в руках: разбор открывают надолго, экран держат
 * включённым (wakeLock в SongViewer), листают автоскроллом. Адресная строка и
 * панель вкладок в таком режиме только отъедают высоту, поэтому `standalone`
 * здесь не украшение — это плюс полтора-два десятка строк песни на экране.
 *
 * Next отдаёт файл по /manifest.webmanifest и сам ставит на него <link> в
 * <head>. Отдельная ссылка в разметке не нужна.
 *
 * ── Про iOS ─────────────────────────────────────────────────────────────────
 *
 * Safari читает манифест с iOS 16.4; на более старых работают только
 * apple-мета-теги, поэтому они заданы отдельно (`appleWebApp` в app/layout.tsx)
 * — вместе покрывают и старые версии, и новые. Иконку для домашнего экрана iOS
 * берёт НЕ отсюда, а из apple-touch-icon: см. app/apple-icon.png и
 * scripts/make-icons.mjs.
 */
export default function manifest(): MetadataRoute.Manifest {
  return {
    // `id` фиксирует личность приложения. Без него ею становится `start_url`, и
    // однажды изменив стартовый адрес, мы получили бы у уже установивших второе
    // приложение вместо обновления первого.
    id: '/',
    name: `${SITE_NAME} — ${SITE_TAGLINE}`,
    // Подпись под иконкой. Короткая намеренно: длинные названия система режет
    // многоточием, и от них остаётся огрызок.
    short_name: SITE_NAME,
    description:
      'Аккорды песен на гитару и укулеле: текст с аккордами над словами, ' +
      'аппликатуры, транспонирование и капо.',
    lang: 'ru',
    dir: 'ltr',
    start_url: '/',
    scope: '/',
    display: 'standalone',
    // Ориентацию НЕ фиксируем: портрет удобен для текста, но табулатуру
    // («e|--3--5--|») читают в альбомной — там строка не переносится.
    background_color: '#0e0d0b',
    theme_color: '#0e0d0b',
    categories: ['music', 'education', 'entertainment'],
    // Одна и та же картинка заявлена и как обычная, и как maskable — то есть
    // годится и «как есть», и под системную маску. По спеке это пишется одним
    // значением `purpose: 'any maskable'`, но тип в Next такого не принимает,
    // поэтому здесь две записи на файл; смысл тот же.
    //
    // Maskable она потому, что рисунок помещается в «безопасную зону»: он
    // занимает середину 22–78% кадра, а система обрезает всё за пределами
    // центральных 80%. Если картинку поменяют на более размашистую, maskable
    // отсюда придётся убрать — иначе Android срежет ей края.
    icons: [
      { src: '/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
      { src: '/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'maskable' },
      { src: '/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
      { src: '/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
    ],
    // Долгое нажатие по иконке (Android; iOS их не показывает). Только то, до
    // чего иначе идти через несколько экранов.
    shortcuts: [
      { name: 'Аккорды для укулеле', short_name: 'Укулеле', url: '/ukulele' },
      { name: 'Мои песни', short_name: 'Мои песни', url: '/songs' },
    ],
  };
}
