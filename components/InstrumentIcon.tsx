import type { InstrumentId } from '@/lib/chords/instruments';

/**
 * Иконки инструментов — простые контуры: головка грифа, гриф, корпус, розетка.
 *
 * Различаются пропорциями, а не деталями: гитара занимает бокс целиком
 * (высота 20 из 24, корпус шириной 9.2, выраженная талия), укулеле заметно
 * меньше и короче (высота 16, корпус 7) — так силуэты читаются рядом даже на
 * 17 пикселях, где любая мелкая деталь сливается.
 */
export function InstrumentIcon({
  instrument,
  size = 18,
  className,
}: {
  instrument: InstrumentId;
  size?: number;
  className?: string;
}) {
  const isUkulele = instrument === 'ukulele';

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.7"
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden
    >
      {isUkulele ? (
        /* Масштаб от центра — укулеле чуть крупнее прежнего, но всё ещё
           заметно меньше гитары. Толщина линии поделена на тот же
           коэффициент, иначе контур стал бы жирнее гитарного. */
        <g transform="translate(12 12) scale(1.12) translate(-12 -12)" strokeWidth={1.7 / 1.12}>
          {/* Короткая головка и короткий гриф */}
          <path d="M10.9 5h2.2v1.8h-2.2z" />
          <path d="M12 6.8v5.7" />
          {/* Небольшой корпус */}
          <path d="M12 12.5c1.8.1 2.7 1 2.7 2.1 0 .8-.5 1.2-.5 2 0 .9 1.3 1.1 1.3 2.1 0 1.4-1.5 2.3-3.5 2.3s-3.5-.9-3.5-2.3c0-1 1.3-1.2 1.3-2.1 0-.8-.5-1.2-.5-2 0-1.1.9-2 2.7-2.1Z" />
          <circle cx="12" cy="15.6" r="1" />
        </g>
      ) : (
        /* Повёрнута на 45° против часовой — гитара «лежит» грифом вверх-влево.
           Габарит контура 20×9.2, после поворота вписывается в 24 с запасом. */
        <g transform="rotate(-45 12 12)">
          {/* Длинная головка и длинный гриф */}
          <path d="M10.5 2h3v2h-3z" />
          <path d="M12 4v7" />
          {/* Крупный корпус с талией */}
          <path d="M12 11c2.4.1 3.5 1.3 3.5 2.6 0 1.3-1 1.7-1 2.8 0 1.2 2.1 1.5 2.1 2.8 0 1.7-2.1 2.8-4.6 2.8s-4.6-1.1-4.6-2.8c0-1.3 2.1-1.6 2.1-2.8 0-1.1-1-1.5-1-2.8C8.5 12.3 9.6 11.1 12 11Z" />
          <circle cx="12" cy="15" r="1.25" />
        </g>
      )}
    </svg>
  );
}
