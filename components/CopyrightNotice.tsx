import Link from 'next/link';
import { COPYRIGHT_EMAIL, copyrightMailto } from '@/lib/contact';

/**
 * Тихая строка внизу страницы разбора: чей это текст и куда писать, если
 * разбор нужно снять.
 *
 * Стоит именно здесь, а не только в подвале, потому что правообладатель почти
 * никогда не приходит на главную. Он приходит из поиска СРАЗУ на страницу
 * конкретной песни — и ему нужно, чтобы адрес был на ней же, а не через два
 * перехода. Заодно ссылка `mailto:` подставляет адрес этой страницы в тело
 * письма: обращение без точного URL — первая причина уточняющей переписки.
 *
 * Серверный компонент: `COPYRIGHT_EMAIL` читается из окружения без префикса
 * NEXT_PUBLIC_ и в клиентском бандле был бы пустым (см. lib/contact.ts).
 */
export function CopyrightNotice({ pageUrl }: { pageUrl: string }) {
  return (
    <p className="song-copyright print-hide">
      Права на текст и музыку принадлежат их авторам и правообладателям. Разбор опубликован
      пользователем.{' '}
      {COPYRIGHT_EMAIL ? (
        <a href={copyrightMailto(COPYRIGHT_EMAIL, pageUrl)}>Сообщить о нарушении</a>
      ) : (
        <Link href="/copyright">Сообщить о нарушении</Link>
      )}
    </p>
  );
}
