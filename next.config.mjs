/**
 * Заголовки безопасности.
 *
 * Раньше сайт не отдавал ни одного, зато отдавал `X-Powered-By: Next.js` —
 * то есть сообщал стек и не сообщал ничего полезного. Набор ниже ничего не
 * ломает и не требует правок в разметке.
 *
 * CSP здесь НЕ задаётся — он в [middleware.ts](./middleware.ts): ему нужен
 * одноразовый nonce на каждый ответ, а статический заголовок такого не умеет.
 */
const securityHeaders = [
  // Content-Type из ответа больше не «уточняется» браузером по содержимому.
  // Прямо связано с маршрутами картинок: /covers и /avatars отдают то, что
  // когда-то загрузил пользователь, и угадывание типа там совсем ни к чему.
  { key: 'X-Content-Type-Options', value: 'nosniff' },

  // Чужому сайту уходит только источник, и только по https. Внутри сайта
  // полный адрес сохраняется.
  { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },

  // Показывать сайт во фрейме незачем, а кликджекинг так исключается. DENY, а
  // не SAMEORIGIN, чтобы не расходиться с `frame-ancestors 'none'` из CSP:
  // в современных браузерах побеждает CSP, и разные значения только путали бы
  // при чтении заголовков.
  { key: 'X-Frame-Options', value: 'DENY' },

  // Только https. Без `preload`: попадание в список браузеров необратимо, и
  // это решение владельца домена, а не значение по умолчанию в конфиге.
  {
    key: 'Strict-Transport-Security',
    value: 'max-age=63072000; includeSubDomains',
  },

  // Своя вкладка не делится контекстом с чужими: окно, открывшее нас (или
  // открытое нами), не получает ссылку на наш `window`. Это закрывает утечки
  // через межоконные ссылки и разговоры вида «а сколько у тебя фреймов».
  //
  // `-allow-popups`, а не голый `same-origin`, — и это ровно тот случай, о
  // котором предупреждал прежний комментарий здесь. Вход через Telegram идёт
  // всплывающим окном, а `same-origin` разрывает связь между ним и открывшей
  // страницей: окно авторизуется, но ответ вернуть уже некуда, и вход молча
  // ничего не делает. `-allow-popups` сохраняет связь с окнами, которые
  // открыли МЫ САМИ, и по-прежнему не даёт чужой странице получить ссылку на
  // наше окно — то есть отдаётся ровно столько, сколько нужно виджету.
  { key: 'Cross-Origin-Opener-Policy', value: 'same-origin-allow-popups' },

  // Отключаем то, чем сайт не пользуется. ВАЖНО: `screen-wake-lock` в списке
  // нет намеренно — читалка держит экран включённым, пока идёт разбор
  // (navigator.wakeLock в components/SongViewer.tsx), и запрет сломал бы ровно
  // эту функцию.
  {
    key: 'Permissions-Policy',
    value: 'camera=(), microphone=(), geolocation=(), payment=(), usb=()',
  },
];

/** @type {import('next').NextConfig} */
const nextConfig = {
  // Чтобы открыть dev-сервер с телефона в той же сети, добавьте сюда адрес
  // своей машины (напр. '192.168.1.42'). Захардкоженного адреса здесь
  // намеренно нет: на чужой машине он всё равно не тот.
  allowedDevOrigins: [],

  // Версию фреймворка каждому встречному сообщать незачем.
  poweredByHeader: false,

  async headers() {
    return [{ source: '/:path*', headers: securityHeaders }];
  },
};

export default nextConfig;
